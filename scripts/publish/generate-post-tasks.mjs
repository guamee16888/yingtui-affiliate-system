import { CORE_COLLECTIONS, loadCollection, loadContentRules, saveCollection } from "../lib/core-data.mjs";
import { checkTaskDuplicateRisk } from "../lib/duplicate-checker.mjs";
import { readJson } from "../lib/file-store.mjs";
import { createTaskId, todayString } from "../lib/ids.mjs";
import { extractExternalLinks } from "../lib/text-normalizer.mjs";
import { fileURLToPath } from "node:url";

export async function generatePostTasks() {
  const latest = await readJson("data/latest.json", null);
  if (!latest?.tools?.length) throw new Error("data/latest.json has no tools. Run npm run daily first.");
  const [tools, topics, copyLibrary, postTasks, postLedger, xAccounts, assignments, users, accountHealth, contentRules] = await Promise.all([
    loadCollection(CORE_COLLECTIONS.tools),
    loadCollection(CORE_COLLECTIONS.topics),
    loadCollection(CORE_COLLECTIONS.copyLibrary),
    loadCollection(CORE_COLLECTIONS.postTasks),
    loadCollection(CORE_COLLECTIONS.postLedger),
    loadCollection(CORE_COLLECTIONS.xAccounts),
    loadCollection(CORE_COLLECTIONS.assignments),
    loadCollection(CORE_COLLECTIONS.users),
    loadCollection(CORE_COLLECTIONS.accountHealth),
    loadContentRules()
  ]);
  const { tasks, stats } = buildPostTasks({
    date: latest.date || todayString(),
    latestTools: latest.tools,
    tools: tools.items,
    topics: topics.items,
    copyLibrary: copyLibrary.items,
    existingTasks: postTasks.items,
    ledger: postLedger.items,
    xAccounts: xAccounts.items,
    assignments: assignments.items,
    users: users.items,
    accountHealth: accountHealth.items,
    contentRules
  });
  await saveCollection(CORE_COLLECTIONS.postTasks, { ...postTasks, items: tasks });
  return stats;
}

export function buildPostTasks({ date, latestTools = [], tools = [], topics = [], copyLibrary = [], existingTasks = [], ledger = [], xAccounts = [], assignments = [], users = [], accountHealth = [], contentRules }) {
  const tasks = [...existingTasks];
  const stats = {
    generated: 0,
    skippedExisting: 0,
    blocked: 0,
    highRisk: 0,
    pendingReview: 0,
    missingAccount: 0,
    missingCopy: 0
  };
  const context = { tasks, ledger, xAccounts, users, accountHealth, copyLibrary, contentRules };

  for (const latestTool of latestTools) {
    const toolId = latestTool.toolId;
    const tool = tools.find((item) => item.toolId === toolId) ?? latestTool;
    const copy = preferredCopy(copyLibrary, toolId);
    if (!copy) {
      stats.missingCopy += 1;
      continue;
    }
    const topic = topics.find((item) => item.topicId === copy.topicId) ?? null;
    const accountId = latestTool.accountRecommendation?.primary?.accountId || firstActiveAccountId(xAccounts);
    if (!accountId) stats.missingAccount += 1;
    const assignment = assignments.find((item) => item.accountId === accountId && item.active !== false);
    const account = xAccounts.find((item) => item.accountId === accountId);
    const workspaceId = latestTool.workspaceId || account?.workspaceId || assignment?.workspaceId || "workspace_default";
    const taskId = createTaskId(date, accountId || "no_account", copy.copyId);
    if (tasks.some((item) => item.taskId === taskId)) {
      stats.skippedExisting += 1;
      continue;
    }
    const task = {
      taskId,
      date,
      workspaceId,
      laneId: latestTool.laneId || topic?.laneId || copy.laneId || "",
      sourceCandidateId: latestTool.sourceCandidateId || topic?.sourceCandidateId || copy.sourceCandidateId || "",
      accountId,
      assignedTo: assignment?.userId || "",
      managerUserId: "",
      toolId,
      toolName: latestTool.name || tool.name || "",
      toolUrl: latestTool.url || tool.officialUrl || tool.productHuntUrl || "",
      topicId: copy.topicId,
      copyId: copy.copyId,
      copyText: copy.copyText,
      variantType: copy.variantType,
      status: "pending_review",
      approvalStatus: "pending",
      publishMode: "manual",
      autoPublishEnabled: false,
      requiresFinalApproval: true,
      publishWindow: "",
      scheduledAt: "",
      copiedAt: "",
      postedAt: "",
      postedUrl: "",
      feedbackDueAt: "",
      metrics: defaultMetrics(),
      duplicateCheckResult: {},
      riskFlags: [],
      externalLinks: extractExternalLinks(copy.copyText),
      affiliateLinkUsed: latestTool.affiliateLink || "",
      notes: topic?.painPoint ? `Topic: ${topic.painPoint}` : "Generated by Foundation v4 task generator.",
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    };
    const duplicateCheckResult = checkTaskDuplicateRisk({ task, context });
    task.duplicateCheckResult = duplicateCheckResult;
    task.riskFlags = duplicateCheckResult.flags.map((flag) => flag.type);
    if (duplicateCheckResult.riskLevel === "block") {
      task.status = "draft";
      task.approvalStatus = "rejected";
      stats.blocked += 1;
    } else if (duplicateCheckResult.riskLevel === "high") {
      task.status = "draft";
      task.approvalStatus = "pending";
      stats.highRisk += 1;
    } else {
      stats.pendingReview += 1;
    }
    tasks.push(task);
    stats.generated += 1;
  }

  return { tasks, stats };
}

function preferredCopy(copyLibrary, toolId) {
  const copies = copyLibrary.filter((item) => item.toolId === toolId && !["used", "rejected", "archived"].includes(item.status));
  return copies.find((item) => item.variantType === "shortPost")
    ?? copies.find((item) => item.variantType === "painPointHook")
    ?? copies[0]
    ?? null;
}

function firstActiveAccountId(accounts) {
  return accounts.find((item) => item.status === "active" || item.active)?.accountId || "";
}

function defaultMetrics() {
  return {
    impressions: 0,
    likes: 0,
    bookmarks: 0,
    replies: 0,
    reposts: 0,
    clicks: 0,
    profileVisits: 0
  };
}

function printStats(stats) {
  console.log("Post task generation complete");
  console.log(`- Generated: ${stats.generated}`);
  console.log(`- Pending review: ${stats.pendingReview}`);
  console.log(`- Blocked: ${stats.blocked}`);
  console.log(`- High risk: ${stats.highRisk}`);
  console.log(`- Missing account: ${stats.missingAccount}`);
  console.log(`- Missing copy: ${stats.missingCopy}`);
  console.log(`- Skipped existing: ${stats.skippedExisting}`);
}

if (fileURLToPath(import.meta.url) === process.argv[1]) {
  const stats = await generatePostTasks();
  printStats(stats);
}
